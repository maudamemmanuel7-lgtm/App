@app.route("/admin/outstanding-fees")
@role_required("admin")
def outstanding_fees_report():
    connection = get_db_connection()

    current_term = connection.execute("""
        SELECT id, academic_year, term_name
        FROM academic_terms
        ORDER BY id DESC
        LIMIT 1
    """).fetchone()

    if not current_term:
        connection.close()
        flash("No academic term has been registered.")
        return redirect(url_for("dashboard"))

    report = connection.execute("""
        SELECT
            students.student_id,
            students.fullname,
            students.current_class,

            SUM(
                CASE
                    WHEN fees.term_id = %s
                    THEN fees.amount_due - COALESCE(paid.amount_paid, 0)
                    ELSE 0
                END
            ) AS current_term_balance,

            SUM(
                CASE
                    WHEN fees.term_id != %s
                    THEN fees.amount_due - COALESCE(paid.amount_paid, 0)
                    ELSE 0
                END
            ) AS previous_term_arrears,

            SUM(
                fees.amount_due - COALESCE(paid.amount_paid, 0)
            ) AS total_balance

        FROM students

        JOIN fees
            ON students.student_id = fees.student_id

        LEFT JOIN (
            SELECT
                fee_id,
                SUM(amount_paid) AS amount_paid
            FROM payments
            GROUP BY fee_id
        ) AS paid
            ON fees.id = paid.fee_id

        WHERE students.account_status = 'active'

        GROUP BY students.student_id, students.fullname, students.current_class

        HAVING SUM(fees.amount_due - COALESCE(paid.amount_paid, 0)) > 0

        ORDER BY students.fullname ASC

    """, (current_term["id"], current_term["id"])).fetchall()

    connection.close()

    return render_template(
        "outstanding_fees_report.html",
        report=report,
        current_term=current_term
    )


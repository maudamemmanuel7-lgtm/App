@app.route("/admin/payments", methods=["GET", "POST"])
@role_required("admin")
def admin_payments():
    connection = get_db_connection()

    if request.method == "POST":
        fee_id = request.form.get("fee_id")
        amount = request.form.get("amount", "").strip()
        payment_method = request.form.get("payment_method", "").strip()
        reference = request.form.get("reference", "").strip()

        try:
            fee_id = int(fee_id)
            amount = float(amount)

            fee = connection.execute("""
                SELECT
                    fees.*,
                    COALESCE(SUM(payments.amount_paid), 0) AS amount_paid
                FROM fees
                LEFT JOIN payments ON fees.id = payments.fee_id
                WHERE fees.id = %s
                GROUP BY fees.id
            """, (fee_id,)).fetchone()

            if not fee:
                flash("Selected fee record was not found.")

            else:
                balance = fee["amount_due"] - fee["amount_paid"]

                if amount <= 0:
                    flash("Enter a valid payment amount.")

                elif amount > balance:
                    flash("Payment cannot exceed the outstanding balance.")

                elif not payment_method:
                    flash("Please select a payment method.")

                else:
                    connection.execute("""
                        INSERT INTO payments (
                            student_id,
                            fee_id,
                            amount_paid,
                            payment_method,
                            reference,
                            recorded_by
                        )
                        VALUES (%s, %s, %s, %s, %s, %s)
                    """, (
                        fee["student_id"],
                        fee_id,
                        amount,
                        payment_method,
                        reference,
                        session["user_id"]
                    ))

                    connection.commit()
                    flash("Payment recorded successfully.")

        except (ValueError, TypeError):
            flash("Please enter valid payment details.")

        except psycopg.Error:
            connection.rollback()
            flash("An error occurred while recording the payment.")

    outstanding_fees = connection.execute("""
        SELECT
            fees.id,
            fees.student_id,
            students.fullname,
            fees.description,
            fees.amount_due,
            academic_terms.academic_year,
            academic_terms.term_name,
            fees.amount_due -
            COALESCE(SUM(payments.amount_paid), 0) AS balance
        FROM fees
        JOIN students ON fees.student_id = students.student_id
        JOIN academic_terms ON fees.term_id = academic_terms.id
        LEFT JOIN payments ON fees.id = payments.fee_id
        GROUP BY fees.id, students.fullname, academic_terms.academic_year,
                 academic_terms.term_name
        HAVING fees.amount_due - COALESCE(SUM(payments.amount_paid), 0) > 0
        ORDER BY students.fullname ASC
    """).fetchall()

    connection.close()

    return render_template(
        "admin_payments.html",
        outstanding_fees=outstanding_fees
    )


@app.route("/teacher/results", methods=["GET", "POST"])
@role_required("teacher")
def teacher_results():
    connection = get_db_connection()

    assignments = connection.execute("""
        SELECT
            teacher_subjects.class_id,
            teacher_subjects.subject_id,
            classes.class_name,
            classes.academic_year,
            subjects.subject_name
        FROM teacher_subjects
        JOIN classes ON teacher_subjects.class_id = classes.id
        JOIN subjects ON teacher_subjects.subject_id = subjects.id
        WHERE teacher_subjects.teacher_user_id = %s
    """, (session["user_id"],)).fetchall()

    terms = connection.execute("""
        SELECT *
        FROM academic_terms
        ORDER BY id DESC
    """).fetchall()

    if request.method == "POST":

        assignment_value = request.form.get("assignment", "")
        term_value = request.form.get("term_id", "")

        try:
            class_id, subject_id = map(int, assignment_value.split("|"))
            term_id = int(term_value)
        except (ValueError, TypeError):
            connection.close()
            return "Invalid selection.", 400

        selected_assignment = next(
            (item for item in assignments
             if item["class_id"] == class_id
             and item["subject_id"] == subject_id),
            None
        )

        selected_term = next(
            (term for term in terms if term["id"] == term_id),
            None
        )

        if selected_assignment is None or selected_term is None:
            connection.close()
            return "Invalid class, subject or academic term.", 400

        students = connection.execute("""
            SELECT student_id, fullname, current_class, academic_year
            FROM students
            WHERE current_class = %s
            AND academic_year = %s
            AND account_status = 'active'
            ORDER BY fullname ASC
        """, (
            selected_assignment["class_name"],
            selected_assignment["academic_year"]
        )).fetchall()
        if request.form.get("save_results") == "1":

            scores = []

            for student in students:
                student_id = student["student_id"]

                try:
                    class_exercises = float(
                        request.form.get("class_exercises_" + student_id)
                    )
                    assignments_score = float(
                        request.form.get("assignments_" + student_id)
                    )
                    examination = float(
                        request.form.get("examination_" + student_id)
                    )

                except (ValueError, TypeError):
                    connection.close()
                    return "Invalid or missing score entered.", 400

                if not all(0 <= score <= 100 for score in
                           [class_exercises, assignments_score, examination]):
                    connection.close()
                    return "Scores must be between 0 and 100.", 400

                scores.append((
                    student_id,
                    class_exercises,
                    assignments_score,
                    examination
                ))

            try:
                for score in scores:
                    cursor = connection.execute("""
                        INSERT INTO results
                        (student_id, class_id, subject_id, term_id,
                         class_exercises, assignments, examination,
                         entered_by, status)
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, 'draft')
                        ON CONFLICT(student_id, subject_id, term_id)
                        DO UPDATE SET
                            class_exercises = excluded.class_exercises,
                            assignments = excluded.assignments,
                            examination = excluded.examination,
                            entered_by = excluded.entered_by
                        WHERE results.status = 'draft'
                    """, (
                        score[0],
                        class_id,
                        subject_id,
                        term_id,
                        score[1],
                        score[2],
                        score[3],
                        session["user_id"]
                    ))

                    if cursor.rowcount == 0:
                        connection.rollback()
                        connection.close()
                        return "A result is already published and cannot be overwritten.", 400

                connection.commit()
                connection.close()

                return "Student results saved successfully as drafts."

            except psycopg.IntegrityError:
                connection.rollback()
                connection.close()
                return "Could not save results. Please check the student records.", 400

        connection.close()

        return render_template(
            "teacher_results.html",
            assignments=assignments,
            terms=terms,
            students=students,
            selected_assignment=selected_assignment,
            selected_term=selected_term
        )

    connection.close()

    return render_template(
        "teacher_results.html",
        assignments=assignments,
        terms=terms
    )


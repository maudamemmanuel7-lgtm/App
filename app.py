@app.route("/student/fees")
@role_required("student")
def student_fees():
    student_id = session.get("student_id")

    connection = get_db_connection()
    current_term = connection.execute("""
        SELECT id, academic_year, term_name
        FROM academic_terms
        ORDER BY id DESC
        LIMIT 1
    """).fetchone()

    fees = connection.execute("""
        SELECT
            fees.id,
            fees.term_id,
            fees.description,
            fees.amount_due,
            academic_terms.academic_year,
            academic_terms.term_name,
            COALESCE(SUM(payments.amount_paid), 0) AS amount_paid
        FROM fees
        JOIN academic_terms ON fees.term_id = academic_terms.id
        LEFT JOIN payments ON fees.id = payments.fee_id
        WHERE fees.student_id = %s
        GROUP BY fees.id, academic_terms.academic_year, academic_terms.term_name
        ORDER BY fees.id DESC
    """, (student_id,)).fetchall()
    total_balance = sum(
        fee["amount_due"] - fee["amount_paid"]
        for fee in fees
    )
    current_term_balance = sum(
        fee["amount_due"] - fee["amount_paid"]
        for fee in fees
        if fee["term_id"] == current_term["id"]
    )

    previous_term_arrears = total_balance - current_term_balance

    connection.close()

    return render_template(
        "student_fees.html",
        fees=fees,
        total_balance=total_balance,
        current_term=current_term,
        current_term_balance=current_term_balance,
        previous_term_arrears=previous_term_arrears
    )

